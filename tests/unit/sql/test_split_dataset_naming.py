        (["lbae", "lbds"], {}),
        (["mha", "mhb", "mhd", "mhg", "mhlb"], {}),
        (["re", "relsub"], {}),
        (["aplbef", "aplbs"], {}),
        (["suppqssw", "suppqsswls", "suppqscg"], {}),
        (["suppdmdm", "suppdmmmm"], {}),
        (["ss1", "ss2"], {"ss": ["ss1", "ss2"]}),
        (["qscgi", "qscgi2"], {}),
